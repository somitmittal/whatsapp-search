const RECENT_KEY = 'wa_recent_emojis';
const MAX_RECENTS = 24;

/**
 * Retrieves the user's recently used emojis from localStorage.
 */
export function getRecentEmojis() {
  try {
    if (typeof localStorage === 'undefined') return [];
    const raw = localStorage.getItem(RECENT_KEY);
    if (!raw) return [];
    const list = JSON.parse(raw);
    return Array.isArray(list) ? list : [];
  } catch {
    return [];
  }
}

/**
 * Records an emoji to recents in localStorage.
 */
export function recordRecentEmoji(emoji) {
  try {
    if (typeof localStorage === 'undefined' || !emoji) return;
    const current = getRecentEmojis().filter((e) => e !== emoji);
    const updated = [emoji, ...current].slice(0, MAX_RECENTS);
    localStorage.setItem(RECENT_KEY, JSON.stringify(updated));
  } catch {
    // Ignore storage errors (private browsing, quota)
  }
}

/**
 * Searches the emoji catalog based on user input.
 * Matches on emoji character, name, keywords, and category.
 *
 * @param {string} query - The search term (e.g. "heart", "laugh", "dog")
 * @param {object} [options]
 * @param {string} [options.category] - Filter by category ID ('smileys', 'people', etc.)
 * @param {number} [options.limit=120] - Max results
 * @returns {Array<{ emoji: string, name: string, category: string, keywords: string[] }>}
 */
export function searchEmojis(query, { category = null, limit = 120 } = {}) {
  const q = String(query || '').trim().toLowerCase();

  let pool = EMOJI_CATALOG;
  if (category && category !== 'all') {
    pool = pool.filter((item) => item.category === category);
  }

  if (!q) {
    return pool.slice(0, limit);
  }

  // Scoring engine for rank matching
  const scored = [];
  for (const item of pool) {
    let score = 0;

    // Direct emoji match
    if (item.emoji === q) {
      score += 100;
    }

    // Exact keyword match (e.g. searching "love" matches keyword "love")
    if (item.keywords.some((k) => k === q)) {
      score += 50;
    } else if (item.keywords.some((k) => k.startsWith(q))) {
      // Keyword prefix match (e.g. searching "laug" matches "laugh")
      score += 30;
    } else if (item.keywords.some((k) => k.includes(q))) {
      // Keyword substring match
      score += 15;
    }

    // Name match
    const nameLower = item.name.toLowerCase();
    if (nameLower === q) {
      score += 40;
    } else if (nameLower.startsWith(q)) {
      score += 25;
    } else if (nameLower.includes(q)) {
      score += 10;
    }

    if (score > 0) {
      scored.push({ item, score });
    }
  }

  // Sort descending by score
  scored.sort((a, b) => b.score - a.score);
  return scored.slice(0, limit).map((s) => s.item);
}
